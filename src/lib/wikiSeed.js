export async function seedWikiIfEmpty() {
  const pages = await listPages();

  if (pages.length > 0) return pages;

  for (const page of SEED) {
    await savePage({ slug: page.slug, title: page.title, body: page.body, order: page.order, by: 'sayyes' });
  }

  return listPages();
}
