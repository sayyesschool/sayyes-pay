// Перезаливка. Возвращает, что обновилось и что сохранили как есть.
// В ключе версии лежит не только номер, но и список страниц, которые мы
// не тронули: по нему вики показывает «в коде есть новая версия».
export async function syncSeed({ force = false, slug = null } = {}) {
  const stored = await kvGet(VERSION_KEY);
  const storedVersion = Number(stored && typeof stored === 'object' ? stored.v : stored) || 0;
  const storedKept = (stored && typeof stored === 'object' && Array.isArray(stored.kept)) ? stored.kept : [];
  const pages = await listPages();
  const bySlug = {};

  for (const page of pages) bySlug[page.slug] = page;

  // Ничего не поменялось и никто не просил — базу не трогаем вовсе.
  if (!force && storedVersion >= SEED_VERSION && pages.length) return { updated: 0, kept: storedKept };

  const kept = [];
  let updated = 0;

  for (const item of SEED) {
    if (slug && item.slug !== slug) continue;

    const page = bySlug[item.slug];

    // Страницу правил человек — его текст важнее нашего. Обновим только по кнопке.
    if (page && page.updatedBy && !force) {
      kept.push(item.slug);
      continue;
    }

    await savePage({ ...item, seed: true });
    updated++;
  }

  // Обновляли одну страницу по кнопке — версию не двигаем, просто вычёркиваем её
  // из списка расхождений.
  const nextKept = slug ? storedKept.filter(item => item !== slug) : kept;

  await kvSet(VERSION_KEY, { v: slug ? storedVersion : SEED_VERSION, kept: nextKept });

  return { updated, kept: nextKept };
}

// Страницы, которые разошлись с кодом: правлены руками и пропущены при перезаливке.
export async function staleSlugs() {
  const stored = await kvGet(VERSION_KEY);

  if (!stored || typeof stored !== 'object' || !Array.isArray(stored.kept)) return [];

  return stored.kept;
}

export async function seedWiki() {
  return syncSeed();
}
