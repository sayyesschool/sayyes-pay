// Страницы досыпаются по одной: если такой ещё нет, кладём. Уже существующие
// не трогаем никогда — их правят менеджеры, и перезаписать чужую правку нельзя.
export async function seedWikiIfEmpty() {
  const pages = await listPages();
  const have = new Set(pages.map(page => page.slug));
  let added = 0;

  for (const page of SEED) {
    if (have.has(page.slug)) continue;

    await savePage({ slug: page.slug, title: page.title, body: page.body, order: page.order, by: 'sayyes' });
    added++;
  }

  return added ? listPages() : pages;
}
