// Ограничения по дням: когда ведущая доступна не весь день.
//
// Здесь перечислены РАЗРЕШЁННЫЕ часы — всё остальное в эти даты закрыто.
// Даты без записи в этом списке работают как обычно, по полной сетке.
//
// Время — в базовом поясе расписания (UTC+3), том же, в котором хранятся ключи слотов.
// Закрытые слоты отдаются наружу вместе с занятыми: для воронки и для бота это
// одно и то же — место, которое нельзя выбрать. Так ограничение работает везде сразу,
// без правки сеток в двух местах.
//
// Уже существующие записи не трогаются: человек, записавшийся раньше на закрытое
// теперь время, остаётся в расписании — его переносят руками.
export const DAY_HOURS = {
  '2026-09-07': ['15:00', '16:00', '17:00', '18:00', '19:00'],
  '2026-09-10': ['14:00', '15:00', '16:00', '17:00', '18:00'],
  '2026-09-11': ['10:00', '11:00', '12:00', '13:00']
};

// Сетка шире, чем у воронки и у бота по отдельности: они исторически
// расходятся (в боте нет 10:00 и 12:30, в воронке есть). Берём объединение,
// чтобы ограничение закрывало любой слот, который где-то может появиться.
const GRID = [];

for (let h = 10; h <= 20; h++) {
  GRID.push(String(h).padStart(2, '0') + ':00');
  if (h < 20) GRID.push(String(h).padStart(2, '0') + ':30');
}

export function isSlotClosed(slotKey) {
  const [date, time] = String(slotKey || '').split('_');
  const allowed = DAY_HOURS[date];

  return Boolean(allowed) && !allowed.includes(time);
}

// Все закрытые слоты одним списком — в том же виде, что и занятые.
export function closedSlots() {
  const out = [];

  for (const date of Object.keys(DAY_HOURS)) {
    const allowed = DAY_HOURS[date];

    for (const time of GRID) {
      if (!allowed.includes(time)) out.push(date + '_' + time);
    }
  }

  return out;
}
