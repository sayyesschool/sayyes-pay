// Реанимация не пришедших на пробный урок.
//
// Тексты — из документов Ольги от 03.09.2026: емейл-цепочка и телеграм-цепочка.
// Обещания в обоих каналах одинаковые, жанр разный: в почте развёрнуто, в боте
// человек пишет человеку. Подписывает Кристина.
//
// Отсчёт идёт от МОМЕНТА ОТМЕТКИ «не пришёл», а не от даты урока: отметку ставят
// руками и иногда с задержкой в несколько дней, иначе первые два касания ушли бы
// пачкой в один час.
//
// Касания: +1 день, +4 дня, +11 дней от старта.

import { clientWhen } from '@/lib/time';

const SITE = 'https://www.sayyestoenglish.com/';
const DAY = 24 * 60 * 60 * 1000;

export const REVIVE_OFFSETS_DAYS = [1, 4, 11];

// Персональная ссылка открывает воронку сразу на выборе времени. Человек уже
// заполнял форму один раз, второй раз он этого не сделает.
export function reviveLink(booking) {
    return SITE + 'learn_easy?reschedule=' + encodeURIComponent(booking.id || '');
}

// Строка под формат из квиза. «Хочу сначала попробовать» — без строки: там
// человек ещё не выбрал формат, и обещать подбор группы нечестно.
function segmentLine(booking) {
    const format = String((booking.quizAnswers || {})['Формат'] || '');

    if (/групп/i.test(format)) {
        return 'Заодно скажем, в какую группу вы попадаете по уровню и когда ближайший старт.';
    }

    if (/индивид/i.test(format)) {
        return 'Заодно подберём преподавателя под вашу цель и уровень и покажем, у кого есть свободные окна в ваше время.';
    }

    return '';
}

function firstName(booking) {
    const name = String(booking.name || '').trim();

    if (!name || name.includes('@')) return '';

    return name.split(' ')[0];
}

function greeting(booking) {
    const name = firstName(booking);

    return name ? name + ', здравствуйте!' : 'Здравствуйте!';
}

// Дата урока в письме уместна, только если урок был недавно. У накопленной базы
// он был неделю назад, и напоминание точной даты работает против нас.
function lessonMention(booking, startedAt) {
    const marked = booking.attendanceMarkedAt ? new Date(booking.attendanceMarkedAt).getTime() : 0;
    const fresh = marked && (startedAt - marked) < 3 * DAY;

    if (!fresh) return 'Вы записывались к нам на пробный урок английского, но встреча не состоялась.';

    return 'Вы записывались к нам на пробный урок английского ' + clientWhen(booking) + ', но встреча не состоялась.';
}

