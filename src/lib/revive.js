export function reviveKeyboard(booking) {
    return {
        inline_keyboard: [
            [{ text: '📅 Выбрать время', url: reviveLink(booking) }],
            [{ text: 'Напишу позже', callback_data: 'revive_later:' + booking.id }]
        ]
    };
}

export function reviveDueAt(startedAt, step) {
    return startedAt + REVIVE_OFFSETS_DAYS[step - 1] * DAY;
}

// --- Почта ---

export function reviveSubject(booking, step) {
    const name = firstName(booking);

    if (step === 1) return name ? name + ', ваш пробный урок остался за вами' : 'Ваш пробный урок остался за вами';
    if (step === 2) return name ? name + ', два приёма, которые снимают языковой барьер' : 'Два приёма, которые снимают языковой барьер';

    return 'Последнее письмо про ваш пробный урок';
}

function esc(value) {
    return String(value == null ? '' : value)
        .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function p(text) {
    return '<tr><td style="font-size:15px;line-height:1.7;color:#3a3a3a;padding-bottom:16px">' + text + '</td></tr>';
}

function h1(text) {
    return '<tr><td style="font-size:22px;font-weight:800;line-height:1.3;padding-bottom:14px">' + text + '</td></tr>';
}

function cta(booking, label) {
    return '<tr><td style="padding:6px 0 6px">'
        + '<a href="' + reviveLink(booking) + '" style="display:inline-block;padding:13px 24px;'
        + 'background:#5B2D8E;color:#fff;border-radius:100px;font-size:15px;font-weight:700;'
        + 'text-decoration:none">' + label + '</a></td></tr>';
}

function signature() {
    return '<tr><td style="font-size:15px;line-height:1.7;color:#3a3a3a;padding-top:8px">'
        + 'See you soon!<br>Кристина, школа английского языка Say Yes! 💜</td></tr>';
}

